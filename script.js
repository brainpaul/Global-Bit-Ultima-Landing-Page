// Testimonial Slider
const slider = document.querySelector('.testimonial-slider');
const slides = document.querySelectorAll('.testimonial-slide');
const prevBtn = document.querySelector('.testimonial-prev');
const nextBtn = document.querySelector('.testimonial-next');
const dotsContainer = document.querySelector('.testimonial-dots');

let currentIndex = 0;
let autoInterval;

function updateSlider() {
    const slideWidth = slides[0]?.offsetWidth || 0;
    slider.style.transform = `translateX(-${currentIndex * slideWidth}px)`;
    document.querySelectorAll('.testimonial-dot').forEach((dot, i) => {
        dot.classList.toggle('active', i === currentIndex);
    });
}

function createDots() {
    if (!dotsContainer) return;
    dotsContainer.innerHTML = '';
    slides.forEach((_, i) => {
        const dot = document.createElement('div');
        dot.classList.add('testimonial-dot');
        if (i === currentIndex) dot.classList.add('active');
        dot.addEventListener('click', () => { currentIndex = i; updateSlider(); resetAuto(); });
        dotsContainer.appendChild(dot);
    });
}

function nextSlide() { currentIndex = (currentIndex + 1) % slides.length; updateSlider(); }
function prevSlide() { currentIndex = (currentIndex - 1 + slides.length) % slides.length; updateSlider(); }
function startAuto() { autoInterval = setInterval(nextSlide, 6000); }
function resetAuto() { clearInterval(autoInterval); startAuto(); }

if (slides.length) {
    createDots();
    updateSlider();
    startAuto();
    window.addEventListener('resize', () => updateSlider());
    if (prevBtn && nextBtn) {
        prevBtn.addEventListener('click', () => { prevSlide(); resetAuto(); });
        nextBtn.addEventListener('click', () => { nextSlide(); resetAuto(); });
    }
}

// Gallery Lightbox
const galleryImages = document.querySelectorAll('.gallery-item img');
const lightbox = document.getElementById('lightbox');
const lightboxImg = document.getElementById('lightbox-img');
const closeBtn = document.querySelector('.lightbox-close');

galleryImages.forEach(img => {
    img.addEventListener('click', (e) => {
        e.stopPropagation();
        lightbox.style.display = 'flex';
        lightboxImg.src = img.src;
        lightboxImg.alt = img.alt;
    });
});

function closeLightbox() {
    lightbox.style.display = 'none';
}

if (closeBtn) closeBtn.addEventListener('click', closeLightbox);
lightbox.addEventListener('click', (e) => {
    if (e.target === lightbox) closeLightbox();
});

// Optional: close with Escape key
document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && lightbox.style.display === 'flex') {
        closeLightbox();
    }
});